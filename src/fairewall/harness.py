"""Synthetic agent-traffic generator for the shadow-mode report.

Everything this module produces is SYNTHETIC: invented by the fAIrewall authors
to exercise the engine before a real partner log exists. The log carries a
``_meta.synthetic = true`` header, and ``fairewall.report`` stamps the banner on
every report built from it. Never present this output as customer data.

The adversary is RANDOM, not a fixed list. Each attack is assembled from large
pools of phrasings, then pushed through randomly chosen mutations (typos,
look-alike letters, invisible characters, encodings, other languages, hiding in
ordinary text) and paired with randomly chosen targets. A different seed gives a
different attack set, so the engine cannot be tuned to a known list. Pass
``seed=None`` (the default) for a fresh one each run; the seed used is recorded
in the log header so any run can be reproduced.

Limits worth stating plainly: the generator is still written by the authors, so
it cannot imagine every real attack. A low "got through" rate here is a floor on
how good the engine is, never proof that real attackers will be stopped.
"""


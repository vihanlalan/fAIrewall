_TOPIC = ["delivery date", "invoice copy", "refund status", "GST receipt", "address change",
          "warranty claim", "size exchange", "bulk pricing", "payment link", "return window"]
_SYL = ["ka", "lo", "mi", "ra", "tu", "zen", "bo", "qui", "far", "dex", "nu", "vel", "sar", "tek", "mon"]
_TLD = [".com", ".net", ".io", ".co", ".biz", ".info", ".xyz", ".online"]


def _domain(rng: random.Random) -> str:
    return "".join(rng.choice(_SYL) for _ in range(rng.randint(2, 3))) + rng.choice(_TLD)


def _external_address(rng: random.Random) -> str:
    return "%s%s@%s" % (rng.choice(_FIRST).lower(), rng.choice(["", str(rng.randint(1, 99)), ".ops"]),
                        _domain(rng))


